#[cfg(test)]
mod tests {
    #[test]
    fn site_policies_are_in_perl_critic_order() {
        let names: Vec<&str> = super::SITE_POLICIES.iter().map(|(n, _)| *n).collect();
        let mut sorted = names.clone();
        sorted.sort_unstable();
        assert_eq!(names, sorted);
    }
}
